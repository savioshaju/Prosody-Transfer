def audit_copula_pipeline():
    analyser = Analyser()
    generator = Generator()
    analysis_layer = AnalysisLayer()
    copula_layer = CopulaLayer()
    
    results = {}
    
    for cat_name, items in corpus.items():
        cat_stats = {
            "total": len(items),
            "mlmorph_only_success": 0,
            "mlmorph_only_fail": 0,
            "fallback_triggered": 0,
            "fallback_success_after_fail": 0,
            "fallback_incorrect": 0,
            "fallback_redundant": 0,
            "mlmorph_plus_fallback_success": 0,
            "rows": []
        }
        
        for sent, word, expected in items:
            # 1. Analyse using AnalysisLayer
            analyses, status = analysis_layer.analyze_word(word)
            selected = analyses[0] if analyses else None
            raw_analysis = selected.raw_analysis if selected else ""
            
            # --- EVALUATE MLMORPH-ONLY GENERATION ---
            mlmorph_gen_output = None
            if raw_analysis and "<" in raw_analysis:
                target = f"{raw_analysis}ആണ്<aff>"
                gen_res = generator.generate(target)
                if gen_res:
                    # Filter sandhi if case
                    css = copula_layer.detect_css(word, selected) if selected else ""
                    if css:
                        sandhi_patterns = copula_layer.get_sandhi_css_candidates(css)
                        filtered = [g[0] for g in gen_res if any(p in g[0] for p in sandhi_patterns)]
                        mlmorph_gen_output = filtered[0] if filtered else gen_res[0][0]
                    else:
                        mlmorph_gen_output = gen_res[0][0]

            # --- EVALUATE SURFACE FALLBACK ---
            surface_output = attach_aanu_surface(word)
            
            # --- EVALUATE COPULA LAYER PIPELINE (MLMorph + Fallback) ---
            pipeline_form, case_pres, cop_path = copula_layer.transform_word(word, selected)
            
            # Re-analysis of pipeline form
            reanalyses = analyser.analyse(pipeline_form)
            reanalysis_raw = reanalyses[0][0] if reanalyses else "NO_REANALYSIS"
            
            # Evaluate metrics
            # Consider sandhi variants matching expected as success
            mlmorph_ok = (mlmorph_gen_output == expected or (mlmorph_gen_output and mlmorph_gen_output.replace("യ്ക്കാണ്", "ക്കാണ്") == expected.replace("യ്ക്കാണ്", "ക്കാണ്")))
            pipeline_ok = (pipeline_form == expected or (pipeline_form and pipeline_form.replace("യ്ക്കാണ്", "ക്കാണ്") == expected.replace("യ്ക്കാണ്", "ക്കാണ്")))
            
            fallback_was_triggered = (mlmorph_gen_output is None)
            
            if mlmorph_ok:
                cat_stats["mlmorph_only_success"] += 1
                if not fallback_was_triggered:
                    cat_stats["fallback_redundant"] += 1
            else:
                cat_stats["mlmorph_only_fail"] += 1
                
            if fallback_was_triggered:
                cat_stats["fallback_triggered"] += 1
                if pipeline_ok:
                    cat_stats["fallback_success_after_fail"] += 1
                else:
                    cat_stats["fallback_incorrect"] += 1
                    
            if pipeline_ok:
                cat_stats["mlmorph_plus_fallback_success"] += 1
                
            cat_stats["rows"].append({
                "sentence": sent,
                "input_word": word,
                "expected": expected,
                "selected_analysis": raw_analysis,
                "mlmorph_gen_output": mlmorph_gen_output,
                "mlmorph_only_success": mlmorph_ok,
                "fallback_triggered": fallback_was_triggered,
                "fallback_output": surface_output,
                "pipeline_output": pipeline_form,
                "copula_path": cop_path,
                "reanalysis_raw": reanalysis_raw,
                "is_correct": pipeline_ok
            })
            
        results[cat_name] = cat_stats
        
    out_file = os.path.join("Datasets", "copula_pipeline_empirical_audit.json")
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
        
    print(f"Audit completed across {sum(len(v) for v in corpus.values())} test cases. Results saved to {out_file}\n")
    
    # Print summary table
    print("=" * 120)
    print(f"{'Category':<24} | {'Total':<6} | {'MLMorph Alone':<14} | {'MLMorph+Fallback':<18} | {'Fallback Trig':<14} | {'Fallback Needed':<16}")
    print("-" * 120)
    for cat, stats in results.items():
        print(f"{cat:<24} | {stats['total']:<6} | {stats['mlmorph_only_success']}/{stats['total']:<12} | {stats['mlmorph_plus_fallback_success']}/{stats['total']:<16} | {stats['fallback_triggered']}/{stats['total']:<12} | {stats['fallback_success_after_fail']:<16}")
    print("=" * 120)

if __name__ == "__main__":
    audit_copula_pipeline()
